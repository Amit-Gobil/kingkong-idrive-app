#!/usr/bin/env python3
"""The KingKong logo for the app: src/logo.js (runs of colour, the renderer has no pictures in layer mode) and the icon."""
import json, sys
from pathlib import Path
from PIL import Image
A = Path(__file__).resolve().parents[1] / 'apps/kingkong_drag'
src = Image.open(sys.argv[1]).convert('RGBA')
W, H = 270, 90
small = src.resize((W, H), Image.LANCZOS)
rgb = Image.new('RGB', (W, H), (10, 10, 10)); rgb.paste(small, mask=small.split()[3])
q = rgb.quantize(colors=10, dither=Image.Dither.NONE)
pal = q.getpalette()[:30]
colors = ['#%02x%02x%02x' % tuple(pal[i * 3:i * 3 + 3]) for i in range(10)]
alpha, idx, runs = small.split()[3].load(), q.load(), []
for y in range(H):
    x = 0
    while x < W:
        if alpha[x, y] < 128: x += 1; continue
        c, start = idx[x, y], x
        while x < W and alpha[x, y] >= 128 and idx[x, y] == c: x += 1
        runs += [y, start, x - start, c]
(A / 'src/logo.js').write_text("'use strict';\n/* Generated by tools/gen_logo.py: [y, x, length, colour] for each run of pixels. */\nmodule.exports = " + json.dumps({'w': W, 'h': H, 'colors': colors, 'runs': runs}, separators=(',', ':')) + ";\n")
print(len(runs) // 4, 'runs')
im = Image.new('RGBA', (140, 140), (10, 10, 10, 255))
L = src.resize((132, 44), Image.LANCZOS); im.alpha_composite(L, (4, 48))
im.save(A / 'package/rhmiData/variantGroups/Common/images/kingkong_drag_icon.png')
